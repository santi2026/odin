import {readFile,writeFile,mkdir,readdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import postcss from 'postcss';
const root=resolve(import.meta.dirname,'..');
const folders=(await readdir(root)).filter(name=>name==='preview'||name.startsWith('preview-'));
await mkdir(resolve(root,'theme-light'),{recursive:true});
const brightness=([r,g,b])=>(r*.2126+g*.7152+b*.0722)/255;
function rgb(token){const hex=token.slice(1);return (hex.length===3?hex.split('').map(c=>c+c):hex.match(/../g)).slice(0,3).map(c=>parseInt(c,16));}
function lightColor(token,role){
  const values=token.startsWith('#')?rgb(token):token.match(/[\d.]+/g).slice(0,3).map(Number),level=brightness(values);
  if(role==='background')return level<.38?(level<.07?'#f3f5f9':level<.13?'#ffffff':'#e8eef7'):token;
  if(role==='border')return level<.5?'#cbd5e2':token;
  if(role==='text')return level>.5?(values[0]>values[2]*1.12?'#88601b':level>.85?'#182538':'#405e87'):token;
  return level<.38?lightColor(token,'background'):lightColor(token,'text');
}
const colors=/#(?:[\da-f]{8}|[\da-f]{6}|[\da-f]{3})(?![\da-f])|rgba?\([^)]*\)/gi;
export function convert(css){
  const tree=postcss.parse(css);
  tree.walkAtRules(rule=>{if(/keyframes|font-face|import/.test(rule.name))rule.remove();});
  tree.walkRules(rule=>{
    // Keep clock faces, photographic backgrounds and decorative illustrations intentional.
    if(/clock-date|clock-stage|clock-flip|flip-digit|flip-tile|clock-analog|analog-face|analog-hand|clock-digital|clock-standard|tcf-flip|tool-art|tool-visual|tool-cover|cover-|moon-disc/.test(rule.selector)){rule.remove();return;}
    const background=rule.nodes.find(node=>node.type==='decl'&&/^(background|background-color)$/.test(node.prop))?.value||'';
    const bgToken=background.match(/^#[\da-f]{3,6}\b/i)?.[0];
    const strongBackground=bgToken&&brightness(rgb(bgToken))>=.38&&brightness(rgb(bgToken))<.75;
    rule.walkDecls(decl=>{
      const prop=decl.prop;
      if(prop.startsWith('--clock-')){decl.remove();return;}
      if(prop==='color-scheme'){decl.value='light';return;}
      let role=prop.startsWith('--')?'variable':/^background/.test(prop)?'background':/border|outline/.test(prop)?'border':/^(color|fill|stroke|accent-color)$/.test(prop)?'text':null;
      if(!role){decl.remove();return;}
      if(role==='text'&&strongBackground)return;
      const changed=decl.value.replace(colors,token=>{
        const mapped=lightColor(token,role);
        if(mapped===token)return token;
        const alpha=token.startsWith('rgba')?Number(token.match(/[\d.]+/g)[3]):token.startsWith('#')&&token.length===9?parseInt(token.slice(7),16)/255:null;
        return alpha==null?mapped:`rgba(${rgb(mapped).join(',')},${alpha})`;
      });
      if(changed===decl.value&&!decl.value.includes('var(')){decl.remove();return;}
      decl.value=changed;
    });
    if(!rule.nodes.length){rule.remove();return;}
    rule.selector=rule.selectors.map(selector=>{selector=selector.trim();return /^(:root|html)(?=\b|\s|\.|:|\[|$)/.test(selector)?selector.replace(/^(:root|html)/,'html[data-theme="light"]'):`html[data-theme="light"] ${selector}`;}).join(',');
  });
  return tree.toString();
}
for(const folder of folders){
  let html;try{html=await readFile(resolve(root,folder,'index.html'),'utf8');}catch{continue;}
  const sheets=[];
  for(const match of html.matchAll(/<link[^>]*href="([^"?]+\.css)(?:\?[^"]*)?"[^>]*>/g)){try{sheets.push(await readFile(resolve(root,match[1].replace(/^\//,'')),'utf8'));}catch{}}
  for(const match of html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g))sheets.push(match[1]);
  // Shared centre styles are attached dynamically after the page has loaded.
  sheets.push(await readFile(resolve(root,'time-control.css'),'utf8'));
  await writeFile(resolve(root,'theme-light',`${folder}.css`),'/* Generated by scripts/build-theme.mjs. */\n'+sheets.map(convert).join('\n'));
}
